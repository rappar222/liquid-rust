use crate::sph::particle::Particle;
use std::fs::File;
use std::io::{self, BufWriter, Write};
use std::path::Path;

pub struct PlyExporter;

impl PlyExporter {
    /// Save particles to a binary little-endian PLY file
    pub fn save_binary<P: AsRef<Path>>(
        path: P,
        particles: &[Particle],
        colors: &[[u8; 3]],
    ) -> io::Result<()> {
        let file = File::create(path)?;
        let mut writer = BufWriter::new(file);

        let n = particles.len();
        let header = format!(
            "ply\n\
             format binary_little_endian 1.0\n\
             comment Generated by liquid-rust 3D Fluid Simulator\n\
             element vertex {}\n\
             property float x\n\
             property float y\n\
             property float z\n\
             property float vx\n\
             property float vy\n\
             property float vz\n\
             property float density\n\
             property float pressure\n\
             property uchar red\n\
             property uchar green\n\
             property uchar blue\n\
             end_header\n",
            n
        );

        writer.write_all(header.as_bytes())?;

        for (i, p) in particles.iter().enumerate() {
            let col = if i < colors.len() {
                colors[i]
            } else {
                [60, 140, 230]
            };

            // Write positions
            writer.write_all(&p.position.x.to_le_bytes())?;
            writer.write_all(&p.position.y.to_le_bytes())?;
            writer.write_all(&p.position.z.to_le_bytes())?;

            // Write velocities
            writer.write_all(&p.velocity.x.to_le_bytes())?;
            writer.write_all(&p.velocity.y.to_le_bytes())?;
            writer.write_all(&p.velocity.z.to_le_bytes())?;

            // Write density and pressure
            writer.write_all(&p.density.to_le_bytes())?;
            writer.write_all(&p.pressure.to_le_bytes())?;

            // Write RGB colors
            writer.write_all(&col)?;
        }

        writer.flush()?;
        Ok(())
    }

    /// Save particles to ASCII PLY file
    pub fn save_ascii<P: AsRef<Path>>(
        path: P,
        particles: &[Particle],
        colors: &[[u8; 3]],
    ) -> io::Result<()> {
        let file = File::create(path)?;
        let mut writer = BufWriter::new(file);

        let n = particles.len();
        writeln!(writer, "ply")?;
        writeln!(writer, "format ascii 1.0")?;
        writeln!(writer, "comment Generated by liquid-rust")?;
        writeln!(writer, "element vertex {}", n)?;
        writeln!(writer, "property float x")?;
        writeln!(writer, "property float y")?;
        writeln!(writer, "property float z")?;
        writeln!(writer, "property float vx")?;
        writeln!(writer, "property float vy")?;
        writeln!(writer, "property float vz")?;
        writeln!(writer, "property float density")?;
        writeln!(writer, "property float pressure")?;
        writeln!(writer, "property uchar red")?;
        writeln!(writer, "property uchar green")?;
        writeln!(writer, "property uchar blue")?;
        writeln!(writer, "end_header")?;

        for (i, p) in particles.iter().enumerate() {
            let col = if i < colors.len() {
                colors[i]
            } else {
                [60, 140, 230]
            };
            writeln!(
                writer,
                "{:.5} {:.5} {:.5} {:.4} {:.4} {:.4} {:.2} {:.2} {} {} {}",
                p.position.x,
                p.position.y,
                p.position.z,
                p.velocity.x,
                p.velocity.y,
                p.velocity.z,
                p.density,
                p.pressure,
                col[0],
                col[1],
                col[2],
            )?;
        }

        writer.flush()?;
        Ok(())
    }
}
